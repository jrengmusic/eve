add_text()
{
    pending+=("$@")
}

add_chunk()
{
    chunks+=("${(F)pending}"${pending:+$'\n'}"$1")
    pending=()
}

print_title()
{
    add_text "" "=== $1 ===" "$2"
}

print_row()
{
    local mark=$1
    shift
    local glyphs="|" ruler="|" sequence code glyph

    for sequence in "$@"
    do
        if (( ${#ruler} + ${#mark} + 1 > columns ))
        then
            add_chunk "${glyphs}"$'\n'"${ruler}"
            glyphs="|"
            ruler="|"
        fi

        for code in ${=sequence}
        do
            printf -v glyph "\\U${(l:8::0:)code}"
            glyphs+="$glyph"
        done

        glyphs+="|"
        ruler+="${mark}|"
    done

    add_chunk "${glyphs}"$'\n'"${ruler}"
}

print_size_row()
{
    local line="" code glyph

    for code in "$@"
    do
        printf -v glyph "\\U${(l:8::0:)code}"

        if (( ${(m)#line} + 9 > columns ))
        then
            add_chunk "$line"
            line=""
        fi

        line+="Hx${glyph}xH  "
    done

    add_chunk "$line"
}

print_codepoints()
{
    local line="" code glyph

    for code in "$@"
    do
        printf -v glyph "\\U${(l:8::0:)code}"

        if (( ${(m)#line} + 3 > columns ))
        then
            add_chunk "$line"
            line=""
        fi

        if [[ -z "$line" ]]
        then
            line="${code}:"
        fi

        line+=" $glyph"
    done

    add_chunk "$line"
}

get_chunk_rows()
{
    local line
    REPLY=0

    for line in "${(@f)1}"
    do
        (( REPLY += ${(m)#line} ? (${(m)#line} + columns - 1) / columns : 1 ))
    done
}

